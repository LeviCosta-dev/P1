int conta_mul(int n1, int n2, int i, int qnt)
{
    int m_d_c = mdc(n1, n2);
    int mmc = (n1 * n2) / m_d_c;

    qnt = 49 / mmc;

    return qnt;
}


//----------------------------------------------------------------------------------------//


int mdc(int n1, int n2)
{
    if (n1 % n2 == 0)
    {
        return n2;
    }
    else
    {
        return mdc(n2, n1 % n2);
    }
}


