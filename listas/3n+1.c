//-----------------------------------------------------------------------------------------------------------------------------------------------------//


int tamanho(long long int num, int i)
{
    if (num == 1)
    {
        return i;
    }
    else
    {
        if (num % 2 == 0)
        {
            num = num / 2;
        }
        else
        {
            num = num * 3 + 1;
        }
        return tamanho(num, i + 1);
    }
    
}


//-----------------------------------------------------------------------------------------------------------------------------------------------------//


int chama(int i, int j, int tam, int count)
{
    int aux;
    if (count > j)
    {
        return tam;
    }
    else
    {
        aux = tamanho(count, 1);
        if (aux > tam)
        {
            tam = aux;
        }
        return chama(i, j, tam, count + 1);
    }
}


//--------------------------------------------------------------------------------------//


void ler(void)
{
    int i, j, m;

    if (scanf("%d %d", &i, &j) != EOF)
    {
        int a = i;
        int b = j;
        
        if (i > j)
        {
            a = j;
            b = i;
        }
        m = chama(a, b, 1, a);

        printf("%d %d %d\n", i, j, m);
        
        ler();
    }    
}